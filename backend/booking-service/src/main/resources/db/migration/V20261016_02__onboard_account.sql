CREATE TABLE IF NOT EXISTS booking.onboard_accounts (
    booking_id bigint PRIMARY KEY,
    tour_id uuid NOT NULL,
    status varchar(20) NOT NULL CHECK (status IN ('OPEN', 'SETTLING', 'CLOSED')),
    credit_limit numeric(19,2) CHECK (credit_limit >= 0),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS booking.ledger_entries (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES booking.onboard_accounts(booking_id),
    booking_passenger_id bigint NOT NULL,
    room_id uuid,
    entry_type varchar(10) NOT NULL CHECK (entry_type IN ('CHARGE', 'VOID', 'REFUND')),
    amount numeric(19,2) NOT NULL,
    currency varchar(3) NOT NULL DEFAULT 'VND' CHECK (currency = 'VND'),
    source_type varchar(20) NOT NULL,
    source_usage_id bigint NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    package_benefit_id uuid,
    benefit_quantity integer NOT NULL DEFAULT 0 CHECK (benefit_quantity >= 0),
    actor_id varchar(160),
    client_request_id uuid,
    ref_entry_id bigint REFERENCES booking.ledger_entries(id),
    reason varchar(1000),
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((entry_type = 'CHARGE' AND amount >= 0 AND ref_entry_id IS NULL)
        OR (entry_type IN ('VOID','REFUND') AND amount <= 0 AND ref_entry_id IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_ledger_charge_source
    ON booking.ledger_entries(source_type, source_usage_id) WHERE entry_type = 'CHARGE';
CREATE INDEX IF NOT EXISTS idx_ledger_booking_page ON booking.ledger_entries(booking_id, id DESC);
CREATE INDEX IF NOT EXISTS idx_ledger_correction ON booking.ledger_entries(ref_entry_id);

-- A missing limit means no policy has been configured; it is not an unlimited credit grant.
CREATE TABLE IF NOT EXISTS booking.tour_spending_policies (
    tour_id uuid PRIMARY KEY,
    credit_limit numeric(19,2) NOT NULL CHECK (credit_limit >= 0)
);
