CREATE TABLE IF NOT EXISTS booking.spending_limit_changes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id bigint NOT NULL REFERENCES booking.onboard_accounts(booking_id),
    previous_limit numeric(19,2),
    new_limit numeric(19,2) NOT NULL CHECK (new_limit >= 0),
    reason varchar(1000) NOT NULL,
    actor_id varchar(160) NOT NULL,
    client_request_id uuid NOT NULL UNIQUE,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);
